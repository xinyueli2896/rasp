#!/usr/bin/env python3
"""Sweep data splits; find where the frozen adapter gains most over the AR.

    python -m training.split_sweep --plan  > sweep.sh && bash sweep.sh
    python -m training.split_sweep                       # rank the results

WHAT IS SWEPT
-------------
The rule is translation-equivariant in x, so every starter is structurally
identical and WHICH ones go in a pool matters only through token coverage.
The real axes are therefore sizes, not identities:

    a = |A|            the AR's pretraining pool
    o = |A n B|        the overlap
    b = |B| = 10-a+o   with A u B = SEEN, so nothing is stranded

Requiring every cell non-empty gives a in 2..9 and o in 1..a-1: 36 points,
all of which have an instantiation passing validate_split. One concrete
(A, B) is drawn per point with a fixed seed, so the sweep is reproducible
and the same point always means the same split.

WHAT IS MEASURED
----------------
For each point: pretrain the AR on A, then train the frozen-AR adapter on
B, and report

    delta = adapter_RFA - pretrain_RFA     per cell

TWO WAYS TO READ IT, AND THEY DISAGREE
--------------------------------------
"Greatest increase" is not the same question as "best final accuracy", and
on this sweep they will point at different splits. Delta has a ceiling
built in: a split where the AR baseline is already high cannot show a big
gain however good the adapter is, so ranking by delta systematically
favours splits with a WEAK baseline. A tiny A gives a hopeless AR and
flatters the delta without the adapter being any better.

So the table prints both, and sorts by delta only because that is what was
asked. Read the `final` column alongside it before concluding anything.

The headline cell is `unseen`. Delta on `finetune_only` is close to
tautological -- the AR never saw those starters and the adapter trains on
them -- so a large gain there says little.
"""
from __future__ import annotations

import argparse
import glob
import os
import random
import sys

import numpy as np
import torch

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from data.integer_dataset import SEEN, UNSEEN, validate_split  # noqa: E402
from training.pretrain_integer import CELLS                    # noqa: E402


def enumerate_splits(seed: int = 0, seen=None, unseen=None):
    """-> [(tag, A, B)] one validated instantiation per (a, o) point."""
    seen = list(SEEN if seen is None else seen)
    unseen = list(UNSEEN if unseen is None else unseen)
    n, rng, out = len(seen), random.Random(seed), []
    for a in range(2, n):
        for o in range(1, a):
            found = None
            for _ in range(2000):
                A = rng.sample(seen, a)
                rest = [x for x in seen if x not in A]
                B = sorted(rng.sample(A, o) + rest)
                try:
                    validate_split(sorted(A), B, unseen)
                    found = (sorted(A), B)
                    break
                except ValueError:
                    continue
            if found:
                out.append((f'a{a}o{o}', found[0], found[1]))
    return out


def plan(args, splits):
    j = lambda xs: ' '.join(map(str, xs))
    print('#!/usr/bin/env bash')
    print('# generated by: python -m training.split_sweep --plan')
    print(f'# {len(splits)} splits x {len(args.seeds)} seed(s) x 2 stages')
    print('set -uo pipefail')
    print('cd "$(dirname "${BASH_SOURCE[0]}")" 2>/dev/null || true')
    print(f'GPUS=({" ".join(map(str, args.gpus))})')
    print('mkdir -p run_logs')
    print('''
# Phase 1 then phase 2, because the adapter for a split reads that split's
# AR checkpoint. Within a phase the jobs are independent, one per GPU.
run_wave() {            # run_wave <name=cmd> ...
    local i=0 g pids=() names=()
    for spec in "$@"; do
        g=${GPUS[$((i % ${#GPUS[@]}))]}
        local nm="${spec%%=*}" cmd="${spec#*=}"
        $cmd --device "cuda:$g" >"run_logs/$nm.log" 2>&1 &
        pids+=($!); names+=("$nm"); i=$((i+1))
        if [ ${#pids[@]} -eq ${#GPUS[@]} ]; then
            for k in "${!pids[@]}"; do wait "${pids[$k]}" || echo "FAILED ${names[$k]}" >&2; done
            pids=(); names=()
        fi
    done
    for k in "${!pids[@]}"; do wait "${pids[$k]}" || echo "FAILED ${names[$k]}" >&2; done
}
''')
    for phase, mk in (
        ('phase 1  pretrain', lambda t, A, B, s:
            f'pre_{t}_s{s}=python -m training.pretrain_integer '
            f'--pretrain {j(A)} --adapter_pool {j(B)} --split_tag {t} --seed {s}'),
        ('phase 2  adapter (AR frozen)', lambda t, A, B, s:
            f'ad_{t}_s{s}=python -m training.finetune_adapter_integer '
            f'--mode adapter --pretrain {j(A)} --adapter_pool {j(B)} '
            f'--split_tag {t} --seed {s} '
            f'--ar_ckpt checkpoints/ar_integer_{t}_seed{s}.pt')):
        print(f'\necho "== {phase} =="')
        print('run_wave \\')
        jobs = [mk(t, A, B, s) for t, A, B in splits for s in args.seeds]
        for k, jb in enumerate(jobs):
            print(f'  "{jb}"' + (' \\' if k < len(jobs) - 1 else ''))
    print('\necho; echo "rank with: python -m training.split_sweep"')


def rank(args, splits):
    by_tag = {t: (A, B) for t, A, B in splits}
    rows = []
    for tag, (A, B) in by_tag.items():
        pre = sorted(glob.glob(os.path.join(
            args.ckpt_dir, f'ar_integer_{tag}_seed*.pt')))
        ada = sorted(glob.glob(os.path.join(
            args.ckpt_dir, f'integer_adapter-frozen_{tag}_*seed*.pt')))
        if not pre or not ada:
            continue
        P = {k: np.array([torch.load(f, map_location='cpu',
                                     weights_only=False)['rfa'][k] for f in pre])
             for k in CELLS}
        Ad = {k: np.array([torch.load(f, map_location='cpu',
                                      weights_only=False)['rfa'][k] for f in ada])
              for k in CELLS}
        rows.append(dict(tag=tag, A=A, B=B, n=min(len(pre), len(ada)),
                         pre=P, ada=Ad))
    if not rows:
        print('No completed splits found. Generate and run the plan first:')
        print('  python -m training.split_sweep --plan > sweep.sh && bash sweep.sh')
        return 1

    cell = args.cell
    rows.sort(key=lambda r: r['ada'][cell].mean() - r['pre'][cell].mean(),
              reverse=True)
    print(f'ranked by delta on `{cell}`   (adapter - pretrain), {len(rows)} splits\n')
    print(f'{"split":<8}{"|A|":>4}{"|B|":>4}{"pre_only":>9}{"both":>6}'
          f'{"ft_only":>8}   {"baseline":>9}{"adapter":>9}{"delta":>9}{"n":>3}')
    print('-' * 80)
    for r in rows:
        a, b = len(r['A']), len(r['B'])
        o = len(set(r['A']) & set(r['B']))
        p_, d_ = r['pre'][cell].mean(), r['ada'][cell].mean()
        print(f'{r["tag"]:<8}{a:>4}{b:>4}{a-o:>9}{o:>6}{b-o:>8}   '
              f'{p_:>9.3f}{d_:>9.3f}{d_-p_:>+9.3f}{r["n"]:>3}')

    best_d = rows[0]
    best_f = max(rows, key=lambda r: r['ada'][cell].mean())
    print(f'\nlargest delta  : {best_d["tag"]}  '
          f'{best_d["pre"][cell].mean():.3f} -> {best_d["ada"][cell].mean():.3f}')
    print(f'best final     : {best_f["tag"]}  '
          f'{best_f["pre"][cell].mean():.3f} -> {best_f["ada"][cell].mean():.3f}')
    if best_d['tag'] != best_f['tag']:
        print('\n  These disagree, which is the expected outcome rather than a')
        print('  problem: delta is bounded by how bad the baseline was, so')
        print('  ranking by it favours splits with a weak AR. Quote whichever')
        print('  answers the question you are actually asking, and say which.')
    print(f'\n  A = pretrain pool, B = adapter pool, A u B = all 10 seen '
          f'starters, holdout {UNSEEN}.')
    print(f'  `{cell}` is 31 predictions per starter; with n=1 seed treat the '
          f'ordering as indicative only.')
    return 0


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--plan', action='store_true',
                   help='emit a runnable sweep script instead of ranking')
    p.add_argument('--seeds', type=int, nargs='+', default=[0])
    p.add_argument('--gpus', type=int, nargs='+', default=[0])
    p.add_argument('--cell', choices=CELLS, default='unseen')
    p.add_argument('--only', type=str, nargs='+', default=None,
                   help='Restrict to these split tags, e.g. --only a3o2 a3o1 '
                        'a2o1. Use with --seeds to re-run the candidates from '
                        'a 1-seed sweep properly; the enumeration is '
                        'deterministic, so a tag means the same split.')
    p.add_argument('--enum_seed', type=int, default=0)
    p.add_argument('--ckpt_dir', type=str, default='checkpoints')
    a = p.parse_args()

    splits = enumerate_splits(a.enum_seed)
    if a.only:
        keep = set(a.only)
        missing = keep - {t for t, _, _ in splits}
        if missing:
            raise SystemExit(f'unknown split tag(s): {sorted(missing)}')
        splits = [s_ for s_ in splits if s_[0] in keep]
    return plan(a, splits) or 0 if a.plan else rank(a, splits)


if __name__ == '__main__':
    sys.exit(main())
